const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const path=require('node:path');
const saved=new Map(),window={};
const storage={getItem:key=>saved.get(key)||null,setItem:(key,value)=>saved.set(key,value)};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../static/practice_progress.js'),'utf8'),{window});
const Store=window.PianoProgressStore,store=new Store(storage);
const score={title:'曲目甲',source:{kind:'midi'},notes:[{pitch:60,start:0,end:1},{pitch:62,start:1,end:2}]};
const position={time:1.2,groupIndex:1,mode:'correct',hand:'L',rate:.6,loop:true,loopA:1,loopB:2};
store.save(score,position);
const reopened=new Store(storage);
assert.equal(reopened.get(score).time,1.2);
assert.equal(reopened.get(score).hand,'L');
assert.equal(reopened.get(score).rate,.6);
assert.equal(reopened.get(score).loopA,1);
assert.equal(reopened.last(),reopened.key(score));
const second={...score,title:'曲目乙'};store.save(second,{...position,time:0,rate:1});
assert.equal(store.get(score).time,1.2,'换曲不能覆盖上一首的进度');
assert.equal(store.get(second).rate,1);
const changed={...score,notes:[{pitch:65,start:0,end:1}]};
assert.equal(store.get(changed),null,'不同版本的曲谱不能复用错误位置');
const adapted={...score,title:'适配版',notes:[{pitch:61,start:0,end:1}],key_adaptation:{original_project:score}};
assert.equal(store.key(adapted),store.key(score),'适配和原谱共用同一练习进度');
const last=store.last();store.save({...score,source:{kind:'demo'}},position);
assert.equal(store.last(),last,'启动示例不能覆盖最近练习曲目');
const damaged={getItem:()=>'{broken',setItem(){throw new Error('空间不足');}};
assert.doesNotThrow(()=>new Store(damaged).save(score,position),'存储不可用时仍能练习');
console.log('练习进度：重开恢复、逐曲独立、版本区分、适配原谱、示例保护和存储失败检查通过。');
